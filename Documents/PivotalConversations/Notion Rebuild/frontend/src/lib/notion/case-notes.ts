export async function getRecentCaseNotes(limit: number = 5): Promise<CaseNote[]> {
  return getCaseNotes({ limit });
}

// Get case note stats for a client
export async function getCaseNoteStats(clientId: string): Promise<{
  total: number;
  byType: Record<CaseNoteType, number>;
  bySource: Record<CaseNoteSource, number>;
}> {
  const notes = await getClientCaseNotes(clientId);

  const byType: Record<CaseNoteType, number> = {
    'Internal Note': 0,
    'Client Request': 0,
    'Editing Guideline': 0,
  };

  const bySource: Record<CaseNoteSource, number> = {
    'Slack': 0,
    'Email': 0,
    'Call': 0,
    'Manual': 0,
  };

  notes.forEach((note) => {
    if (note.type && byType[note.type] !== undefined) {
      byType[note.type]++;
    }
    if (note.source && bySource[note.source] !== undefined) {
      bySource[note.source]++;
    }
  });

  return {
    total: notes.length,
    byType,
    bySource,
  };
}

// Delete a case note (archives it in Notion)
export async function deleteCaseNote(id: string): Promise<boolean> {
  try {
    await notion.pages.update({
      page_id: id,
      archived: true,
    });
    return true;
  } catch (error) {
    console.error('Failed to delete case note:', error);
    return false;
  }
}

// Delete multiple case notes
export async function deleteCaseNotes(ids: string[]): Promise<{ deleted: number; failed: number }> {
  let deleted = 0;
  let failed = 0;

  for (const id of ids) {
    const success = await deleteCaseNote(id);
    if (success) deleted++;
    else failed++;
  }

  return { deleted, failed };
}

