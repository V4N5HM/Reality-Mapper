// Paginated case notes query with cursor support for "load more" functionality
export async function getCaseNotesPaginated(options?: {
  clientId?: string;
  type?: CaseNoteType;
  source?: CaseNoteSource;
  pageSize?: number;
  cursor?: string;
  // Fireflies owner filtering
  firefliesOwnerEmail?: string;
  firefliesOwnerEmails?: string[];
  includeNonFireflies?: boolean;
}): Promise<{
  caseNotes: CaseNote[];
  nextCursor: string | null;
  hasMore: boolean;
}> {
  try {
    const filters: any[] = [];

    if (options?.clientId) {
      filters.push({ property: 'Client', relation: { contains: options.clientId } });
    }
    if (options?.type) {
      filters.push({ property: 'Type', select: { equals: options.type } });
    }
    if (options?.source) {
      filters.push({ property: 'Source', select: { equals: options.source } });
    }

    // Filter by Fireflies owner email (single owner)
    if (options?.firefliesOwnerEmail) {
      filters.push({ property: 'Fireflies Owner Email', rich_text: { contains: options.firefliesOwnerEmail } });
    }

    // Filter by multiple Fireflies owner emails
    // If includeNonFireflies is true (Personal Brand team), also include notes without owner
    if (options?.firefliesOwnerEmails && options.firefliesOwnerEmails.length > 0) {
      const ownerFilters: any[] = options.firefliesOwnerEmails.map(email => ({
        property: 'Fireflies Owner Email',
        rich_text: { contains: email }, // Use contains for case-insensitive matching
      }));

      // Only include non-Fireflies notes (empty owner) if explicitly allowed
      if (options.includeNonFireflies) {
        ownerFilters.push({
          property: 'Fireflies Owner Email',
          rich_text: { is_empty: true },
        });
      }

      filters.push({ or: ownerFilters });
    } else if (options?.includeNonFireflies && !options?.firefliesOwnerEmails) {
      // Admin case: no email filter, but includeNonFireflies is true
      // This means show ALL notes (no filter needed)
    }

    const pageSize = options?.pageSize || 100;

    const response = await queryDatabase({
      database_id: DATABASE_IDS.caseNotes,
      filter: filters.length > 0 ? { and: filters } : undefined,
      sorts: [{ property: 'Date', direction: 'descending' }],
      page_size: Math.min(pageSize, 100),
      start_cursor: options?.cursor,
    });

    return {
      caseNotes: response.results.map(transformCaseNote),
      nextCursor: response.has_more ? (response.next_cursor as string) : null,
      hasMore: response.has_more,
    };
  } catch (error) {
    console.error('[Case Notes] Error in getCaseNotesPaginated:', error);
    throw error;
  }
}
